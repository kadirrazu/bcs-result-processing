<?php

namespace App\Services\Viva;

use App\Models\VivaResult;
use App\Services\Exports\AdministrativeXlsxExportService;
use Illuminate\Support\Facades\File;

final class VivaInternalResultExportService
{
    public function __construct(private readonly AdministrativeXlsxExportService $xlsx) {}

    /** @return array{path:string,filename:string,count:int} */
    public function create(string $scope, string $generatedBy, string $examinationName): array
    {
        $allowed = ['all', 'pass', 'fail', 'absent', 'cancelled', 'withheld', 'expelled', 'warning'];
        abort_unless(in_array($scope, $allowed, true), 404);

        $query = VivaResult::query()
            ->join('registrations as r', 'r.id', '=', 'viva_results.registration_id')
            ->select('viva_results.*', 'r.name')
            ->when($scope === 'pass', fn ($q) => $q->where('viva_results.viva_result_status', 'pass'))
            ->when($scope === 'fail', fn ($q) => $q->where('viva_results.viva_result_status', 'fail'))
            ->when($scope === 'absent', fn ($q) => $q->where('viva_results.attendance_status', 'absent'))
            ->when(in_array($scope, ['cancelled', 'withheld', 'expelled'], true), fn ($q) => $q->where('viva_results.status', $scope))
            ->when($scope === 'warning', fn ($q) => $q->where(fn ($nested) => $nested
                ->where('viva_results.validation_status', 'warning')
                ->orWhere('viva_results.quota_mismatch', 1)
                ->orWhere('viva_results.invalid_flag', 1)
                ->orWhere('viva_results.issue_flag', 1)
                ->orWhere('viva_results.high_mark_review', 1)))
            ->orderBy('viva_results.reg');

        $directory = storage_path('app/private/viva/exports');
        File::ensureDirectoryExists($directory);
        $filename = 'internal-viva-'.$scope.'-'.now()->format('Ymd-His').'.xlsx';
        $path = $directory.'/'.$filename;

        $rows = (function () use ($query): \Generator {
            foreach ($query->cursor() as $row) {
                $status = $row->status instanceof \BackedEnum ? $row->status->value : (string) $row->status;
                $result = $row->viva_result_status instanceof \BackedEnum ? $row->viva_result_status->value : (string) $row->viva_result_status;
                yield [
                    (string) $row->user_id,
                    (string) $row->reg,
                    (string) ($row->name ?? ''),
                    (string) $row->code,
                    (string) $row->cadre_category,
                    (string) $row->written_qualified_track,
                    $row->viva_date?->format('Y-m-d'),
                    (string) $row->member_id,
                    $row->attendance_status === 'absent' ? 'ABS' : (float) $row->mark,
                    strtoupper($status),
                    strtoupper($result),
                    is_array($row->viva_fail_reasons) ? implode(', ', $row->viva_fail_reasons) : '',
                    (bool) $row->quota_mismatch,
                    (bool) $row->invalid_flag,
                    (bool) $row->issue_flag,
                    (bool) $row->high_mark_review,
                    (int) ($row->processing_version ?? 0),
                ];
            }
        })();

        $count = $this->xlsx->create(
            $path,
            [
                'Confidentiality' => 'INTERNAL ADMINISTRATIVE USE ONLY',
                'Examination' => $examinationName,
                'Report Scope' => strtoupper($scope),
                'Generated At' => now()->timezone('Asia/Dhaka')->format('d M Y, h:i:s A'),
                'Generated By' => $generatedBy,
            ],
            [
                'USER ID', 'REGISTRATION NUMBER', 'NAME', 'VIVA CODE', 'CATEGORY',
                'WRITTEN QUALIFIED TRACK', 'VIVA DATE', 'MEMBER ID', 'VIVA MARK / ABS',
                'ADMINISTRATIVE STATUS', 'VIVA RESULT', 'FAIL REASON', 'QUOTA MISMATCH',
                'INVALID FLAG', 'ISSUE FLAG', 'HIGH MARK REVIEW', 'PROCESSING VERSION',
            ],
            $rows,
        );

        return compact('path', 'filename', 'count');
    }
}
